use std::io::{self, Write};

use crate::model::{AssOptions, Group, Rgb};

pub fn write_ass<W: Write>(groups: &[Group], options: &AssOptions, out: &mut W) -> io::Result<()> {
    write_header(options, out)?;
    for group in groups {
        if group.words.is_empty() {
            continue;
        }
        let text = render_group_text(group, options.highlight);
        writeln!(
            out,
            "Dialogue: 0,{},{},Default,,0,0,0,,{}",
            format_timestamp(group.start_ms()),
            format_timestamp(group.end_ms()),
            text
        )?;
    }
    Ok(())
}

pub fn render_ass(groups: &[Group], options: &AssOptions) -> String {
    let mut output = Vec::new();
    write_ass(groups, options, &mut output).expect("writing to a byte vector cannot fail");
    String::from_utf8(output).expect("ASS output is valid UTF-8")
}

fn write_header<W: Write>(options: &AssOptions, out: &mut W) -> io::Result<()> {
    let style = &options.style;
    let primary = ass_color(style.primary);
    let secondary = ass_color(style.secondary);
    let outline = ass_color(style.outline_color);
    let back = "&H80000000";
    writeln!(
        out,
        "[Script Info]\n; Script generated by Caption Maker\nScriptType: v4.00+\nPlayResX: {}\nPlayResY: {}\nWrapStyle: 0\nScaledBorderAndShadow: yes",
        options.play_res_x, options.play_res_y
    )?;
    writeln!(
        out,
        "\n[V4+ Styles]\nFormat: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding"
    )?;
    writeln!(
        out,
        "Style: Default,{},{},{},{},{},{},-1,0,0,0,100,100,0,0,1,{},{},{},40,40,{},1",
        style.font_name,
        style.font_size,
        primary,
        secondary,
        outline,
        back,
        format_float(style.outline),
        format_float(style.shadow),
        style.alignment,
        style.margin_v
    )?;
    writeln!(
        out,
        "\n[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"
    )
}

fn render_group_text(group: &Group, highlight: bool) -> String {
    let mut output = String::new();
    let mut cumulative_cs = 0_i64;
    let group_start = i64::from(group.start_ms());

    for word in &group.words {
        let start_ms = i64::from(word.start_ms);
        let end_ms = i64::from(word.end_ms);
        if highlight {
            let gap_cs = rounded_cs(start_ms - group_start) - cumulative_cs;
            if gap_cs > 0 {
                output.push_str(&format!("{{\\k{gap_cs}}}"));
                cumulative_cs += gap_cs;
            }
            let end_cs = rounded_cs(end_ms - group_start);
            let word_cs = (end_cs - cumulative_cs).max(0);
            output.push_str(&format!("{{\\kf{word_cs}}}"));
            cumulative_cs = end_cs;
        }
        output.push_str(&escape_text(&word.text));
        output.push(' ');
    }
    output.pop();
    output
}

fn rounded_cs(milliseconds: i64) -> i64 {
    (milliseconds.max(0) + 5) / 10
}

fn escape_text(text: &str) -> String {
    let normalized = text.replace("\r\n", "\n");
    let mut escaped = String::with_capacity(normalized.len());
    for character in normalized.chars() {
        match character {
            '{' => escaped.push('('),
            '}' => escaped.push(')'),
            '\n' | '\r' => escaped.push_str("\\N"),
            _ => escaped.push(character),
        }
    }
    escaped
}

fn format_timestamp(milliseconds: u32) -> String {
    let centiseconds = (u64::from(milliseconds) + 5) / 10;
    let hours = centiseconds / 360_000;
    let minutes = (centiseconds / 6_000) % 60;
    let seconds = (centiseconds / 100) % 60;
    let fraction = centiseconds % 100;
    format!("{hours}:{minutes:02}:{seconds:02}.{fraction:02}")
}

fn ass_color(rgb: Rgb) -> String {
    format!("&H00{:02X}{:02X}{:02X}", rgb.b, rgb.g, rgb.r)
}

fn format_float(value: f32) -> String {
    let formatted = format!("{value:.2}");
    formatted
        .trim_end_matches('0')
        .trim_end_matches('.')
        .to_owned()
}

/// Hasil validasi ASS. Kumpulan masalah yang ditemukan; kosong = valid.
#[derive(Debug, Default)]
pub struct AssValidation {
    pub errors: Vec<String>,
}

impl AssValidation {
    pub fn is_valid(&self) -> bool {
        self.errors.is_empty()
    }
}

/// Validasi struktural file ASS hasil `render_ass`/`write_ass`.
/// Bukan pengganti verifikasi visual: hanya menangkap kesalahan umum
/// (header hilang, jumlah field Dialogue salah, timestamp tidak valid, Start >= End).
pub fn validate_ass(input: &str) -> AssValidation {
    let mut v = AssValidation::default();
    let mut has_script_info = false;
    let mut has_styles = false;
    let mut has_events = false;
    let mut has_style_default = false;

    for (lineno, line) in input.lines().enumerate() {
        let n = lineno + 1;
        if line == "[Script Info]" {
            has_script_info = true;
        } else if line == "[V4+ Styles]" {
            has_styles = true;
        } else if line == "[Events]" {
            has_events = true;
        } else if let Some(rest) = line.strip_prefix("Dialogue: ") {
            validate_dialogue(n, rest, &mut v);
        } else if line.starts_with("Style: Default,") {
            has_style_default = true;
            if line.split(',').count() < 10 {
                v.errors
                    .push(format!("baris {n}: Style Default field kurang dari 10"));
            }
        } else if line.starts_with("PlayResX:") || line.starts_with("PlayResY:") {
            let val = line.split(':').nth(1).unwrap_or("").trim();
            if val.parse::<u32>().map(|x| x == 0).unwrap_or(true) {
                v.errors.push(format!("baris {n}: {line} bukan angka > 0"));
            }
        }
    }

    if !has_script_info {
        v.errors.push("bagian [Script Info] tidak ditemukan".into());
    }
    if !has_styles {
        v.errors.push("bagian [V4+ Styles] tidak ditemukan".into());
    }
    if !has_events {
        v.errors.push("bagian [Events] tidak ditemukan".into());
    }
    if has_styles && !has_style_default {
        v.errors.push("Style Default tidak ditemukan".into());
    }
    v
}

fn validate_dialogue(lineno: usize, rest: &str, v: &mut AssValidation) {
    // Format: Layer,Start,End,Style,Name,MarginL,MarginR,MarginV,Effect,Text
    // Text boleh mengandung koma, jadi split dengan limit 10.
    let parts: Vec<&str> = rest.splitn(10, ',').collect();
    if parts.len() != 10 {
        v.errors.push(format!(
            "baris {lineno}: Dialogue punya {} field (harus 10)",
            parts.len()
        ));
        return;
    }
    let start = parts[1].trim();
    let end = parts[2].trim();
    let (Ok(s), Ok(e)) = (parse_ass_time(start), parse_ass_time(end)) else {
        v.errors.push(format!(
            "baris {lineno}: timestamp tidak valid ({start} / {end})"
        ));
        return;
    };
    if s >= e {
        v.errors
            .push(format!("baris {lineno}: Start >= End ({start} / {end})"));
    }
}

/// Parse `H:MM:SS.cc` jadi centidetik total.
fn parse_ass_time(s: &str) -> Result<u64, ()> {
    let mut it = s.split(':');
    let h: u64 = it.next().ok_or(())?.parse().map_err(|_| ())?;
    let m: u64 = it.next().ok_or(())?.parse().map_err(|_| ())?;
    let sec_part = it.next().ok_or(())?;
    let (sec, cs) = sec_part.split_once('.').ok_or(())?;
    let sec: u64 = sec.parse().map_err(|_| ())?;
    let cs: u64 = cs.parse().map_err(|_| ())?;
    if m > 59 || sec > 59 || cs > 99 {
        return Err(());
    }
    Ok(h * 360_000 + m * 6_000 + sec * 100 + cs)
}
