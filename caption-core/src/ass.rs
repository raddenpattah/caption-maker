use std::io::{self, Write};

use crate::model::{AssOptions, Group, Rgb};

pub fn write_ass<W: Write>(groups: &[Group], options: &AssOptions, out: &mut W) -> io::Result<()> {
    write_header(options, out)?;
    for group in groups {
        if group.words.is_empty() {
            continue;
        }
        let text = render_group_text(group, options.highlight);
        writeln!(
            out,
            "Dialogue: 0,{},{},Default,,0,0,0,,{}",
            format_timestamp(group.start_ms()),
            format_timestamp(group.end_ms()),
            text
        )?;
    }
    Ok(())
}

pub fn render_ass(groups: &[Group], options: &AssOptions) -> String {
    let mut output = Vec::new();
    write_ass(groups, options, &mut output).expect("writing to a byte vector cannot fail");
    String::from_utf8(output).expect("ASS output is valid UTF-8")
}

fn write_header<W: Write>(options: &AssOptions, out: &mut W) -> io::Result<()> {
    let style = &options.style;
    let primary = ass_color(style.primary);
    let secondary = ass_color(style.secondary);
    let outline = ass_color(style.outline_color);
    let back = "&H80000000";
    writeln!(
        out,
        "[Script Info]\n; Script generated by Caption Maker\nScriptType: v4.00+\nPlayResX: {}\nPlayResY: {}\nWrapStyle: 0\nScaledBorderAndShadow: yes",
        options.play_res_x, options.play_res_y
    )?;
    writeln!(
        out,
        "\n[V4+ Styles]\nFormat: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding"
    )?;
    writeln!(
        out,
        "Style: Default,{},{},{},{},{},{},-1,0,0,0,100,100,0,0,1,{},{},{},40,40,{},1",
        style.font_name,
        style.font_size,
        primary,
        secondary,
        outline,
        back,
        format_float(style.outline),
        format_float(style.shadow),
        style.alignment,
        style.margin_v
    )?;
    writeln!(
        out,
        "\n[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"
    )
}

fn render_group_text(group: &Group, highlight: bool) -> String {
    let mut output = String::new();
    let mut cumulative_cs = 0_i64;
    let group_start = i64::from(group.start_ms());

    for word in &group.words {
        let start_ms = i64::from(word.start_ms);
        let end_ms = i64::from(word.end_ms);
        if highlight {
            let gap_cs = rounded_cs(start_ms - group_start) - cumulative_cs;
            if gap_cs > 0 {
                output.push_str(&format!("{{\\k{gap_cs}}}"));
                cumulative_cs += gap_cs;
            }
            let end_cs = rounded_cs(end_ms - group_start);
            let word_cs = (end_cs - cumulative_cs).max(0);
            output.push_str(&format!("{{\\kf{word_cs}}}"));
            cumulative_cs = end_cs;
        }
        output.push_str(&escape_text(&word.text));
        output.push(' ');
    }
    output.pop();
    output
}

fn rounded_cs(milliseconds: i64) -> i64 {
    (milliseconds.max(0) + 5) / 10
}

fn escape_text(text: &str) -> String {
    let normalized = text.replace("\r\n", "\n");
    let mut escaped = String::with_capacity(normalized.len());
    for character in normalized.chars() {
        match character {
            '{' => escaped.push('('),
            '}' => escaped.push(')'),
            '\n' | '\r' => escaped.push_str("\\N"),
            _ => escaped.push(character),
        }
    }
    escaped
}

fn format_timestamp(milliseconds: u32) -> String {
    let centiseconds = (u64::from(milliseconds) + 5) / 10;
    let hours = centiseconds / 360_000;
    let minutes = (centiseconds / 6_000) % 60;
    let seconds = (centiseconds / 100) % 60;
    let fraction = centiseconds % 100;
    format!("{hours}:{minutes:02}:{seconds:02}.{fraction:02}")
}

fn ass_color(rgb: Rgb) -> String {
    format!("&H00{:02X}{:02X}{:02X}", rgb.b, rgb.g, rgb.r)
}

fn format_float(value: f32) -> String {
    let formatted = format!("{value:.2}");
    formatted
        .trim_end_matches('0')
        .trim_end_matches('.')
        .to_owned()
}
